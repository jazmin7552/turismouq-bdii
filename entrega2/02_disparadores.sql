--        quién (usuario), cuándo (fecha), valor anterior y valor nuevo
--   3. Disparador de FILA: impide solapes de reservas en una misma habitación
--   4. Pruebas con casos reales (sirven de evidencia: capturar la salida)
--
-- Por qué los dos son disparadores COMPUESTOS (COMPOUND TRIGGER):
--   * Auditoría: un disparador de sentencia simple no ve :OLD ni :NEW. El
--     compuesto recoge cada fila afectada (AFTER EACH ROW) y escribe UNA sola vez
--     al terminar la sentencia (AFTER STATEMENT).
--   * Solape: un disparador FOR EACH ROW simple que consulta su propia tabla
--     falla con ORA-04091 (tabla mutante) en los UPDATE. El compuesto recoge cada
--     fila nueva y la valida al final de la sentencia, cuando la tabla ya no está
--     mutando. Así sí funciona tanto en INSERT como en UPDATE.
--
-- Código de error propio: -20001 (solape de reservas).
-- Requisito: haber corrido DDL, carga y 01_paquete_completo.sql.
