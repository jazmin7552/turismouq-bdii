CREATE TABLE auditoria_tarifa (
    id_auditoria    NUMBER          GENERATED BY DEFAULT AS IDENTITY,
    operacion       VARCHAR2(10)    NOT NULL,
    id_tarifa       NUMBER,
    id_habitacion   NUMBER,
    id_temporada    NUMBER,
    precio_anterior NUMBER(10,2),
    precio_nuevo    NUMBER(10,2),
    usuario         VARCHAR2(60)    NOT NULL,
    fecha_cambio    DATE            NOT NULL,
    CONSTRAINT pk_auditoria_tarifa PRIMARY KEY (id_auditoria),
    CONSTRAINT ck_audtarifa_operacion CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE'))
);

COMMENT ON TABLE auditoria_tarifa IS 'Historial de cambios sobre TARIFA: quién, cuándo, valor anterior y nuevo.';

--------------------------------------------------------------------------------
-- 2. DISPARADOR DE SENTENCIA: AUDITORÍA DE TARIFA
--    Una sentencia UPDATE/INSERT/DELETE sobre TARIFA genera un registro por cada
--    fila cuyo precio cambió, todos insertados al terminar la sentencia.
--------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_auditoria_tarifa_sentencia
FOR INSERT OR UPDATE OF precio_noche OR DELETE ON tarifa
COMPOUND TRIGGER

    TYPE t_fila IS RECORD (
        operacion       VARCHAR2(10),
        id_tarifa       tarifa.id_tarifa%TYPE,
        id_habitacion   tarifa.id_habitacion%TYPE,
        id_temporada    tarifa.id_temporada%TYPE,
        precio_anterior tarifa.precio_noche%TYPE,
        precio_nuevo    tarifa.precio_noche%TYPE
    );
    TYPE t_lista IS TABLE OF t_fila INDEX BY PLS_INTEGER;
    v_lista t_lista;

    -- Se ejecuta por cada fila: solo guarda en memoria lo que cambió
    AFTER EACH ROW IS
        v_n PLS_INTEGER;
    BEGIN
        -- Un UPDATE sin cambio real de precio no se audita
        -- (en un disparador compuesto no se permite RETURN, por eso se usa IF)
        IF NOT (UPDATING AND :OLD.precio_noche = :NEW.precio_noche) THEN
            v_n := v_lista.COUNT + 1;
            v_lista(v_n).operacion       := CASE WHEN INSERTING THEN 'INSERT'
                                                 WHEN UPDATING  THEN 'UPDATE'
                                                 ELSE 'DELETE' END;
            v_lista(v_n).id_tarifa       := NVL(:NEW.id_tarifa, :OLD.id_tarifa);
            v_lista(v_n).id_habitacion   := NVL(:NEW.id_habitacion, :OLD.id_habitacion);
            v_lista(v_n).id_temporada    := NVL(:NEW.id_temporada, :OLD.id_temporada);
            v_lista(v_n).precio_anterior := :OLD.precio_noche;   -- NULL en INSERT
            v_lista(v_n).precio_nuevo    := :NEW.precio_noche;   -- NULL en DELETE
        END IF;
    END AFTER EACH ROW;

    -- Se ejecuta una sola vez, al final de la sentencia
    AFTER STATEMENT IS
    BEGIN
        FOR i IN 1 .. v_lista.COUNT LOOP
            INSERT INTO auditoria_tarifa (operacion, id_tarifa, id_habitacion, id_temporada,
                                          precio_anterior, precio_nuevo, usuario, fecha_cambio)
            VALUES (v_lista(i).operacion, v_lista(i).id_tarifa, v_lista(i).id_habitacion,
                    v_lista(i).id_temporada, v_lista(i).precio_anterior,
                    v_lista(i).precio_nuevo, USER, SYSDATE);
        END LOOP;
    END AFTER STATEMENT;

END trg_auditoria_tarifa_sentencia;
/
SHOW ERRORS

--------------------------------------------------------------------------------
-- 3. DISPARADOR DE FILA: IMPEDIR SOLAPE DE RESERVAS EN LA MISMA HABITACIÓN
--    Regla: dos líneas de reserva de una misma habitación no pueden compartir
--    noches cuando ambas pertenecen a reservas PENDIENTE, CONFIRMADA o COMPLETADA.
--    El día del check-out queda libre para el siguiente huésped (10 al 15 y
--    15 al 18 NO se solapan). Una reserva CANCELADA no bloquea la habitación.
--    Se valida en INSERT y en UPDATE de habitación o fechas.
--------------------------------------------------------------------------------
CREATE OR REPLACE TRIGGER trg_evitar_solape_reserva
FOR INSERT OR UPDATE OF id_habitacion, fecha_checkin, fecha_checkout ON reserva_habitacion
COMPOUND TRIGGER

    TYPE t_fila IS RECORD (
        id_linea      reserva_habitacion.id_reserva_habitacion%TYPE,
        id_habitacion reserva_habitacion.id_habitacion%TYPE,
        fecha_in      reserva_habitacion.fecha_checkin%TYPE,
        fecha_out     reserva_habitacion.fecha_checkout%TYPE
    );
    TYPE t_lista IS TABLE OF t_fila INDEX BY PLS_INTEGER;
    v_lista t_lista;

    -- Por cada fila: se recuerda la línea si su reserva no está cancelada
    AFTER EACH ROW IS
        v_estado reserva.estado%TYPE;
        v_n      PLS_INTEGER;
    BEGIN
        SELECT estado INTO v_estado
          FROM reserva
         WHERE id_reserva = :NEW.id_reserva;

        IF v_estado <> 'CANCELADA' THEN
            v_n := v_lista.COUNT + 1;
            v_lista(v_n).id_linea      := :NEW.id_reserva_habitacion;
            v_lista(v_n).id_habitacion := :NEW.id_habitacion;
            v_lista(v_n).fecha_in      := :NEW.fecha_checkin;
            v_lista(v_n).fecha_out     := :NEW.fecha_checkout;
        END IF;
    END AFTER EACH ROW;

    -- Al terminar la sentencia: cada línea recordada se compara con las demás
    AFTER STATEMENT IS
        v_cruces NUMBER;
    BEGIN
        FOR i IN 1 .. v_lista.COUNT LOOP
            SELECT COUNT(*)
              INTO v_cruces
              FROM reserva_habitacion rh
              JOIN reserva r ON r.id_reserva = rh.id_reserva
             WHERE rh.id_habitacion = v_lista(i).id_habitacion
               AND rh.id_reserva_habitacion <> v_lista(i).id_linea
               AND r.estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA')
               AND v_lista(i).fecha_in  < rh.fecha_checkout
               AND v_lista(i).fecha_out > rh.fecha_checkin;

            IF v_cruces > 0 THEN
                RAISE_APPLICATION_ERROR(-20001,
                    'Solape de reservas: la habitación ' || v_lista(i).id_habitacion ||
                    ' ya tiene una reserva activa entre ' ||
                    TO_CHAR(v_lista(i).fecha_in, 'YYYY-MM-DD') || ' y ' ||
                    TO_CHAR(v_lista(i).fecha_out, 'YYYY-MM-DD') || '.');
            END IF;
        END LOOP;
    END AFTER STATEMENT;

END trg_evitar_solape_reserva;
/
SHOW ERRORS

