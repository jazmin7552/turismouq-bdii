-- 4. PRUEBAS (evidencia). Capturar la pestaña "Salida de script".
--------------------------------------------------------------------------------

-- 4.1 Auditoría de TARIFA
--     a) UPDATE de varias filas con una sola sentencia
--     b) UPDATE que no cambia el precio (no debe auditar nada)
--     c) DELETE y re-INSERT de una tarifa
DECLARE
    v_filas      NUMBER;
    v_audit      NUMBER;
    v_antes      NUMBER;
    v_mal        NUMBER;
    v_hab        tarifa.id_habitacion%TYPE;
    v_temp       tarifa.id_temporada%TYPE;
    v_precio     tarifa.precio_noche%TYPE;
    v_id         tarifa.id_tarifa%TYPE;

    PROCEDURE sp_mostrar (p_limite NUMBER) IS
    BEGIN
        FOR r IN (SELECT * FROM (SELECT * FROM auditoria_tarifa ORDER BY id_auditoria)
                   WHERE ROWNUM <= p_limite) LOOP
            DBMS_OUTPUT.PUT_LINE('   ' || RPAD(r.operacion, 7) ||
                ' tarifa ' || RPAD(r.id_tarifa, 6) ||
                ' hab ' || RPAD(r.id_habitacion, 4) ||
                ' anterior ' || LPAD(NVL(TO_CHAR(r.precio_anterior, 'FM999G999G999'), '-'), 9) ||
                ' nuevo ' || LPAD(NVL(TO_CHAR(r.precio_nuevo, 'FM999G999G999'), '-'), 9) ||
                ' | ' || r.usuario || ' | ' || TO_CHAR(r.fecha_cambio, 'YYYY-MM-DD HH24:MI:SS'));
        END LOOP;
    END sp_mostrar;
BEGIN
    DBMS_OUTPUT.PUT_LINE('--- 4.1a UPDATE de todas las tarifas de la habitación 1 (+10.000) ---');
    UPDATE tarifa SET precio_noche = precio_noche + 10000 WHERE id_habitacion = 1;
    v_filas := SQL%ROWCOUNT;

    SELECT COUNT(*) INTO v_audit FROM auditoria_tarifa;
    SELECT COUNT(*) INTO v_mal FROM auditoria_tarifa
     WHERE operacion <> 'UPDATE' OR precio_nuevo <> precio_anterior + 10000 OR id_habitacion <> 1;

    DBMS_OUTPUT.PUT_LINE('   Filas actualizadas en TARIFA : ' || v_filas);
    DBMS_OUTPUT.PUT_LINE('   Registros en AUDITORIA_TARIFA: ' || v_audit);
    DBMS_OUTPUT.PUT_LINE('   Registros incorrectos        : ' || v_mal);
    DBMS_OUTPUT.PUT_LINE('   Resultado: ' || CASE WHEN v_filas = v_audit AND v_mal = 0
                                                  THEN 'OK, una fila de auditoría por cada tarifa cambiada'
                                                  ELSE 'ERROR' END);
    DBMS_OUTPUT.PUT_LINE('   Primeros 3 registros:');
    sp_mostrar(3);

    DBMS_OUTPUT.PUT_LINE(CHR(10) || '--- 4.1b UPDATE que no cambia el precio (habitación 2) ---');
    v_antes := v_audit;
    UPDATE tarifa SET precio_noche = precio_noche WHERE id_habitacion = 2;
    v_filas := SQL%ROWCOUNT;
    SELECT COUNT(*) INTO v_audit FROM auditoria_tarifa;
    DBMS_OUTPUT.PUT_LINE('   Filas tocadas: ' || v_filas || ' | registros nuevos de auditoría: ' || (v_audit - v_antes));
    DBMS_OUTPUT.PUT_LINE('   Resultado: ' || CASE WHEN v_audit = v_antes THEN 'OK, no audita lo que no cambió' ELSE 'ERROR' END);

    DBMS_OUTPUT.PUT_LINE(CHR(10) || '--- 4.1c DELETE y nuevo INSERT de una tarifa (habitación 3) ---');
    SELECT id_tarifa, id_habitacion, id_temporada, precio_noche
      INTO v_id, v_hab, v_temp, v_precio
      FROM (SELECT * FROM tarifa WHERE id_habitacion = 3 ORDER BY id_tarifa)
     WHERE ROWNUM = 1;
    DELETE FROM tarifa WHERE id_tarifa = v_id;
    INSERT INTO tarifa (precio_noche, id_habitacion, id_temporada) VALUES (v_precio + 5000, v_hab, v_temp);
    DBMS_OUTPUT.PUT_LINE('   Últimos registros de auditoría:');
    FOR r IN (SELECT * FROM (SELECT * FROM auditoria_tarifa ORDER BY id_auditoria DESC) WHERE ROWNUM <= 2
               ORDER BY id_auditoria) LOOP
        DBMS_OUTPUT.PUT_LINE('   ' || RPAD(r.operacion, 7) || ' tarifa ' || RPAD(r.id_tarifa, 6) ||
            ' anterior ' || LPAD(NVL(TO_CHAR(r.precio_anterior, 'FM999G999G999'), '-'), 9) ||
            ' nuevo ' || LPAD(NVL(TO_CHAR(r.precio_nuevo, 'FM999G999G999'), '-'), 9) ||
            ' | ' || r.usuario || ' | ' || TO_CHAR(r.fecha_cambio, 'YYYY-MM-DD HH24:MI:SS'));
    END LOOP;

    ROLLBACK;   -- las pruebas no dejan huella en TARIFA ni en AUDITORIA_TARIFA
    DBMS_OUTPUT.PUT_LINE('   (ROLLBACK ejecutado: tarifas originales restauradas)');
END;
