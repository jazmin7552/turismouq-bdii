-- 4.2 Solape de reservas en la misma habitación (habitación 1, junio de 2027,
--     fechas sin reservas existentes) + un caso real tomado de los datos.
--     Cada intento se hace con SAVEPOINT para que un error no arrastre el resto.
DECLARE
    v_linea_a reserva_habitacion.id_reserva_habitacion%TYPE;
    v_linea_c reserva_habitacion.id_reserva_habitacion%TYPE;
    v_id_tmp  reserva_habitacion.id_reserva_habitacion%TYPE;
    v_hab     NUMBER;
    v_in      DATE;
    v_out     DATE;
    v_cruces  NUMBER;

    -- Inserta una reserva (cabecera) y su línea de habitación
    PROCEDURE sp_linea (p_caso   VARCHAR2, p_hab NUMBER, p_in DATE, p_out DATE,
                        p_estado VARCHAR2, p_id OUT NUMBER) IS
        v_res reserva.id_reserva%TYPE;
    BEGIN
        SAVEPOINT sv_caso;
        INSERT INTO reserva (fecha_checkin, fecha_checkout, estado, id_cliente)
        VALUES (p_in, p_out, p_estado, 1)
        RETURNING id_reserva INTO v_res;

        INSERT INTO reserva_habitacion (fecha_checkin, fecha_checkout, num_huespedes, id_reserva, id_habitacion)
        VALUES (p_in, p_out, 1, v_res, p_hab)
        RETURNING id_reserva_habitacion INTO p_id;

        DBMS_OUTPUT.PUT_LINE(RPAD(p_caso, 46) || '-> OK, permitida');
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK TO sv_caso;
            p_id := NULL;
            DBMS_OUTPUT.PUT_LINE(RPAD(p_caso, 46) || '-> ' || SQLERRM);
    END sp_linea;
BEGIN
    DBMS_OUTPUT.PUT_LINE('--- 4.2 Disparador de solape ---');
    DBMS_OUTPUT.PUT_LINE('Base: hab 1 reservada del 2027-06-10 al 2027-06-15');

    sp_linea('A  base 10-15 jun (esperado OK)',          1, DATE '2027-06-10', DATE '2027-06-15', 'CONFIRMADA', v_linea_a);
    sp_linea('B  12-18 jun, solape parcial (-20001)',    1, DATE '2027-06-12', DATE '2027-06-18', 'CONFIRMADA', v_id_tmp);
    sp_linea('C  11-14 jun, dentro de A (-20001)',       1, DATE '2027-06-11', DATE '2027-06-14', 'PENDIENTE',  v_id_tmp);
    sp_linea('D  08-12 jun, solape al inicio (-20001)',  1, DATE '2027-06-08', DATE '2027-06-12', 'CONFIRMADA', v_id_tmp);
    sp_linea('E  15-18 jun, empieza al salir A (OK)',    1, DATE '2027-06-15', DATE '2027-06-18', 'CONFIRMADA', v_linea_c);
    sp_linea('F  12-18 jun en otra habitación 2 (OK)',   2, DATE '2027-06-12', DATE '2027-06-18', 'CONFIRMADA', v_id_tmp);
    sp_linea('G  12-14 jun pero CANCELADA (OK)',         1, DATE '2027-06-12', DATE '2027-06-14', 'CANCELADA',  v_id_tmp);

    -- UPDATE: mover la línea E (15-18) para que choque con A (10-15)
    BEGIN
        UPDATE reserva_habitacion
           SET fecha_checkin = DATE '2027-06-13', fecha_checkout = DATE '2027-06-16'
         WHERE id_reserva_habitacion = v_linea_c;
        DBMS_OUTPUT.PUT_LINE(RPAD('H  UPDATE de E a 13-16 jun (-20001)', 46) || '-> ERROR, el UPDATE no fue bloqueado');
    EXCEPTION
        WHEN OTHERS THEN
            DBMS_OUTPUT.PUT_LINE(RPAD('H  UPDATE de E a 13-16 jun (-20001)', 46) || '-> ' ||
                SUBSTR(SQLERRM, 1, INSTR(SQLERRM || CHR(10), CHR(10)) - 1));
    END;

    -- Caso real: una línea CONFIRMADA ya existente en la base de datos
    SELECT id_habitacion, fecha_checkin, fecha_checkout
      INTO v_hab, v_in, v_out
      FROM (SELECT rh.id_habitacion, rh.fecha_checkin, rh.fecha_checkout
              FROM reserva_habitacion rh
              JOIN reserva r ON r.id_reserva = rh.id_reserva
             WHERE r.estado = 'CONFIRMADA'
             ORDER BY rh.id_reserva_habitacion)
     WHERE ROWNUM = 1;

    DBMS_OUTPUT.PUT_LINE(CHR(10) || 'Caso real: habitación ' || v_hab || ' ya reservada del ' ||
                         TO_CHAR(v_in, 'YYYY-MM-DD') || ' al ' || TO_CHAR(v_out, 'YYYY-MM-DD'));
    sp_linea('I  misma habitación y mismas fechas (-20001)', v_hab, v_in, v_out, 'CONFIRMADA', v_id_tmp);
    sp_linea('J  un día dentro de ese rango (-20001)', v_hab, v_in + 1, v_out + 1, 'CONFIRMADA', v_id_tmp);

    -- Verificación final: ningún par de líneas activas se solapa
    SELECT COUNT(*)
      INTO v_cruces
      FROM reserva_habitacion a
      JOIN reserva ra ON ra.id_reserva = a.id_reserva
      JOIN reserva_habitacion b ON b.id_habitacion = a.id_habitacion
                               AND b.id_reserva_habitacion > a.id_reserva_habitacion
      JOIN reserva rb ON rb.id_reserva = b.id_reserva
     WHERE ra.estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA')
       AND rb.estado IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA')
       AND a.fecha_checkin < b.fecha_checkout
       AND a.fecha_checkout > b.fecha_checkin;

    DBMS_OUTPUT.PUT_LINE(CHR(10) || 'Pares de reservas activas solapadas tras las pruebas: ' || v_cruces ||
                         CASE WHEN v_cruces = 0 THEN '  (OK)' ELSE '  (ERROR)' END);

    ROLLBACK;
    DBMS_OUTPUT.PUT_LINE('(ROLLBACK ejecutado: no quedan reservas de prueba)');
END;
